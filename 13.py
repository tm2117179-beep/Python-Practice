a=4
b=2
print(a+b,end=", ") #Addition operator
print(a-b,end=", ") #substraction operator
print(a*b,end=", ") #multiplication operator
print(a/b,end=", ") #division operator
print(a**b,end=", ") #exponential operator
print(a%b,end=", ") #modulus operator, gives the remainder
print(a//b,end=" ") #floor division operator,   For positive numbers, floor division gives the whole-number part of the quotient.


